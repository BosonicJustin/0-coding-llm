class HashingReader(io.RawIOBase):
    def __init__(self, raw: BinaryIO, digest: Any):
        self.raw = raw
        self.digest = digest

    def readable(self) -> bool:
        return True

    def read(self, size: int = -1) -> bytes:
        data = self.raw.read(size)
        if data:
            self.digest.update(data)
        return data

    def readinto(self, buffer: bytearray) -> int:
        count = self.raw.readinto(buffer)
        if count:
            self.digest.update(memoryview(buffer)[:count])
        return count


class HashingWriter(io.RawIOBase):
    """Hash bytes while forwarding them without taking ownership of the sink."""

    def __init__(self, raw: BinaryIO, digest: Any):
        self.raw = raw
        self.digest = digest

    def writable(self) -> bool:
        return True

    def write(self, data: bytes | bytearray | memoryview) -> int:
        written = self.raw.write(data)
        if written:
            self.digest.update(memoryview(data)[:written])
        return written

    def flush(self) -> None:
        # RawIOBase finalization may flush this non-owning wrapper after the
        # underlying file has already been closed by the caller.
        if not self.raw.closed:
            self.raw.flush()


def fsync_directory(path: Path) -> None:
    descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def atomic_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2, sort_keys=True)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary_name, path)
        fsync_directory(path.parent)
    except BaseException:
        try:
            os.unlink(temporary_name)
        except FileNotFoundError:
            pass
        raise


def durable_unlink(path: Path) -> bool:
    """Remove one published directory entry and durably commit that removal."""
    try:
        path.unlink()
    except FileNotFoundError:
        return False
    fsync_directory(path.parent)
    return True


def require_free_space(path: Path, required_bytes: int, role: str) -> int:
    """Fail closed against the filesystem that actually backs ``path``."""
    free_bytes = int(shutil.disk_usage(path).free)
    if free_bytes < required_bytes:
        raise FreeSpaceSafetyError(role, path, free_bytes, required_bytes)
    return free_bytes


def file_sha256(path: Path, block_size: int = 8 * 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while block := handle.read(block_size):
            digest.update(block)
    return digest.hexdigest()


def bucket_is_code(bucket: str) -> bool:
    return bucket in ("python", "other_code")


def normalize_content(text: str, bucket: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if bucket_is_code(bucket):
        text = unicodedata.normalize("NFC", text)
        lines = [line.rstrip() for line in text.split("\n")]
        while lines and not lines[0]:
            lines.pop(0)
        while lines and not lines[-1]:
            lines.pop()
        return "\n".join(lines)
    text = unicodedata.normalize("NFKC", text).casefold()
    return " ".join(text.split())


def evenly_sample(values: list[str], maximum: int) -> list[str]:
    if len(values) <= maximum:
        return values
    return [values[(index * len(values)) // maximum] for index in range(maximum)]


def near_features(text: str, bucket: str) -> list[str]:
    if bucket_is_code(bucket):
        lines = [" ".join(line.split()) for line in text.splitlines() if line.strip()]
        return evenly_sample(lines, MAX_NEAR_FEATURES)
    words = WORD_RE.findall(text.casefold())
    if len(words) < 5:
        return words
    count = len(words) - 4
    indexes = list(range(count)) if count <= MAX_NEAR_FEATURES else [
        (index * count) // MAX_NEAR_FEATURES for index in range(MAX_NEAR_FEATURES)
    ]
    return [" ".join(words[index : index + 5]) for index in indexes]


def bottom_k_sketch(features: Iterable[str]) -> list[str]:
    heap: list[int] = []
    seen: set[int] = set()
    for feature in features:
        value = xxhash.xxh3_64_intdigest(feature.encode("utf-8"))
        if value in seen:
            continue
        seen.add(value)
        if len(heap) < NEAR_SKETCH_SIZE:
            heapq.heappush(heap, -value)
        elif value < -heap[0]:
            removed = -heapq.heapreplace(heap, -value)
            seen.discard(removed)
    return [f"{value:016x}" for value in sorted(-item for item in heap)]


def quality_metrics(text: str, content: bytes, bucket: str) -> tuple[dict[str, Any], list[str]]:
    lines = text.splitlines() or [text]
    nonempty = [" ".join(line.split()) for line in lines if line.strip()]
    line_count = len(lines)
    nonempty_count = len(nonempty)
    max_line = max((len(line) for line in lines), default=0)
    repeated_fraction = (
        1.0 - len(set(nonempty)) / nonempty_count if nonempty_count else 0.0
    )
    characters = len(text)
    whitespace = sum(character.isspace() for character in text)
    alphanumeric = sum(character.isalnum() for character in text)
    words = WORD_RE.findall(text)
    url_count = len(URL_RE.findall(text))
    code_lines = sum(bool(CODE_LINE_RE.search(line)) for line in lines)
    metrics: dict[str, Any] = {
        "characters": characters,
        "lines": line_count,
        "nonempty_lines": nonempty_count,
        "words": len(words),
        "max_line_chars": max_line,
        "mean_line_chars": round(characters / max(line_count, 1), 3),
        "repeated_line_fraction": round(repeated_fraction, 6),
        "whitespace_fraction": round(whitespace / max(characters, 1), 6),
        "alphanumeric_fraction": round(alphanumeric / max(characters, 1), 6),
        "url_count": url_count,
        "code_line_fraction": round(code_lines / max(line_count, 1), 6),
    }
    flags: list[str] = []
    if not content:
        flags.append("empty")
    if bucket_is_code(bucket) and len(content) < 50:
        flags.append("too_short")
    if not bucket_is_code(bucket) and len(words) < 40:
        flags.append("too_short")
    if "\x00" in text:
        flags.append("null_character")
    if "\ufffd" in text:
        flags.append("replacement_character")
    if max_line > 2_000:
        flags.append("very_long_line")
    if repeated_fraction > 0.5 and nonempty_count >= 10:
        flags.append("high_line_repetition")
    if line_count <= 10 and max_line > 1_000 and bucket_is_code(bucket):
        flags.append("likely_minified")
    if len(words) and url_count / len(words) > 0.05:
        flags.append("high_url_density")
    lowered_head = text[:100_000].casefold()
    if any(marker in lowered_head for marker in GENERATED_MARKERS):
        flags.append("possible_generated")
    if any(pattern.search(text[:1_000_000]) for pattern in SECRET_PATTERNS):
        flags.append("possible_secret")
    return metrics, sorted(set(flags))


