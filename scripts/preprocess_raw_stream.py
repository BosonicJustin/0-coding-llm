class OperationalPreprocessError(RuntimeError):
    """A retryable/configuration-dependent safety failure, not bad source data."""

    error_code = "operational_preprocess_error"

    def error_details(self) -> dict[str, Any]:
        return {"error_code": self.error_code}


class OversizeDocumentError(OperationalPreprocessError):
    """A member was quarantined before materializing an unsafe payload in RAM."""

    error_code = "document_exceeds_operational_byte_cap"

    def __init__(self, member_path: str, declared_bytes: int, maximum_bytes: int):
        self.member_path = member_path
        self.declared_bytes = declared_bytes
        self.maximum_bytes = maximum_bytes
        super().__init__(
            f"Tar member {member_path!r} declares {declared_bytes} bytes, exceeding "
            f"the operational per-document cap of {maximum_bytes} bytes"
        )

    def error_details(self) -> dict[str, Any]:
        return {
            "error_code": self.error_code,
            "quarantine_scope": "archive",
            "quarantined_documents": 1,
            "member_path": self.member_path,
            "declared_bytes": self.declared_bytes,
            "maximum_bytes": self.maximum_bytes,
            "retryable_after_cap_review": True,
        }


class ManifestSafetyError(OperationalPreprocessError):
    """The internal manifest exceeded a separately reviewed operational bound."""

    error_code = "manifest_exceeds_operational_safety_bound"

    def __init__(
        self,
        *,
        limit: str,
        observed: int,
        maximum: int,
        row_index: int | None = None,
    ):
        self.limit = limit
        self.observed = observed
        self.maximum = maximum
        self.row_index = row_index
        row = f" at zero-based row {row_index}" if row_index is not None else ""
        super().__init__(
            f"Internal manifest {limit}{row} is {observed}, exceeding the "
            f"operational maximum of {maximum}"
        )

    def error_details(self) -> dict[str, Any]:
        result: dict[str, Any] = {
            "error_code": self.error_code,
            "manifest_safety_version": MANIFEST_SAFETY_VERSION,
            "quarantine_scope": "archive",
            "limit": self.limit,
            "observed": self.observed,
            "maximum": self.maximum,
            "retryable_after_cap_review": True,
        }
        if self.row_index is not None:
            result["row_index"] = self.row_index
        return result


