def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    if (
        args.workers < 1
        or args.analysis_batch_size < 1
        or args.log_every_documents < 1
        or args.poll_seconds <= 0
        or args.index_batch_size < 1
        or args.status_interval_seconds <= 0
        or args.min_free_gb < 0
        or args.scratch_min_free_gb < 0
        or args.max_manifest_member_bytes < 1
        or args.max_manifest_line_bytes < 1
    ):
        parser.error("counts/intervals must be positive and free-space reserves non-negative")
    if not (
        0
        < args.max_document_bytes
        <= args.max_analysis_batch_bytes
        <= args.max_inflight_bytes
    ):
        parser.error(
            "byte caps must satisfy 0 < --max-document-bytes <= "
            "--max-analysis-batch-bytes <= --max-inflight-bytes"
        )
    if args.require_complete and not args.status:
        parser.error("--require-complete is valid only with --status")
    staging_root = args.staging_root or args.root / "staging" / "preprocess"
    staging_root.mkdir(parents=True, exist_ok=True)
    args.scratch_root.mkdir(parents=True, exist_ok=True)
    ensure_policy_manifest(staging_root, args.benchmark_denylist)
    if args.status:
        snapshot_path = staging_root / "STATUS.json"
        if (
            snapshot_path.exists()
            and not args.require_complete
            and not args.require_closed_collection
        ):
            print(snapshot_path.read_text(encoding="utf-8"), end="")
            return 0
        index: DedupIndex | None = None
        dedup_reason = "optional fingerprint telemetry disabled by --skip-dedup-status"
        if not args.skip_dedup_status:
            try:
                index = DedupIndex(staging_root / "dedup" / "dedup.sqlite3")
            except (OSError, sqlite3.Error, RuntimeError, ValueError) as exc:
                dedup_reason = (
                    "optional fingerprint telemetry unavailable: "
                    f"{type(exc).__name__}: {exc}"
                )
        try:
            snapshot = write_status_snapshot(
                args.root,
                staging_root,
                index,
                quota_path=args.quotas,
                dedup_unavailable_reason=dedup_reason,
            )
        finally:
            if index is not None:
                index.close()
        print(json.dumps(snapshot, indent=2, sort_keys=True))
        gated = args.require_complete or args.require_closed_collection
        return (
            2
            if gated
            and terminal_gate_failures(
                snapshot,
                require_closed_collection=args.require_closed_collection,
            )
            else 0
        )
    lock_handle = (staging_root / ".preprocess.lock").open("a+")
    try:
        fcntl.flock(lock_handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        parser.error(f"Another preprocessor holds {staging_root / '.preprocess.lock'}")
    reconciled = reconcile_published_states(staging_root)
    if reconciled:
        print(
            json.dumps(
                {"event": "legacy_stale_errors_reconciled", "errors_removed": reconciled},
                sort_keys=True,
            ),
            flush=True,
        )
    index = (
        DedupIndex(staging_root / "dedup" / "dedup.sqlite3")
        if args.index_mode in ("inline", "only")
        else None
    )
    stop_request = StopRequest()
    signal.signal(signal.SIGINT, stop_request)
    signal.signal(signal.SIGTERM, stop_request)
    processed_this_run = 0
    last_status_monotonic: float | None = None
    terminal_operational_error: str | None = None

    def maybe_write_status(*, force: bool = False) -> dict[str, Any] | None:
        nonlocal last_status_monotonic
        now = time.monotonic()
        if (
            not force
            and last_status_monotonic is not None
            and now - last_status_monotonic < args.status_interval_seconds
        ):
            return None
        payload = write_status_snapshot(
            args.root,
            staging_root,
            index,
            quota_path=args.quotas,
            dedup_unavailable_reason=(
                "optional fingerprint telemetry disabled during deferred raw audit"
            ),
        )
        last_status_monotonic = time.monotonic()
        return payload

    executor: concurrent.futures.ProcessPoolExecutor | None = None
    if args.index_mode != "only":
        executor = concurrent.futures.ProcessPoolExecutor(
            max_workers=args.workers,
            mp_context=multiprocessing.get_context("spawn"),
            initializer=initialize_worker,
            initargs=(str(args.benchmark_denylist),),
        )
    try:
        while not stop_request.requested:
            made_progress = False
            if args.index_mode in ("inline", "only"):
                assert index is not None
                for report in iter_reports(staging_root):
                    if index.validate_ingested_report(report):
                        continue
                    result = index.ingest(
                        staging_root,
                        report,
                        batch_size=args.index_batch_size,
                    )
                    print(json.dumps({"event": "dedup_ingested", "archive": report["archive"], **result}, sort_keys=True), flush=True)
                    maybe_write_status()
                    made_progress = True
                    processed_this_run += 1
                    if stop_request.requested or (
                        args.max_archives is not None
                        and processed_this_run >= args.max_archives
                    ):
                        break
            limit_reached = (
                args.max_archives is not None
                and processed_this_run >= args.max_archives
            )
            candidates = (
                []
                if args.index_mode == "only" or limit_reached
                else discover_archives(
                    args.root,
                    staging_root,
                    retry_errors=args.retry_errors,
                )
            )
            for candidate in candidates:
                try:
                    require_free_space(
                        args.root,
                        int(args.min_free_gb * 1_000_000_000),
                        "dataset/staging",
                    )
                    require_free_space(
                        args.scratch_root,
                        int(args.scratch_min_free_gb * 1_000_000_000),
                        "scratch/spool",
                    )
                except FreeSpaceSafetyError as exc:
                    terminal_operational_error = str(exc)
                    print(
                        json.dumps(
                            {"event": "free_space_safety_stop", **exc.error_details()},
                            sort_keys=True,
                        ),
                        flush=True,
                    )
                    stop_request.requested = True
                    break
                try:
                    report = process_archive(
                        candidate,
                        staging_root,
                        executor,
                        args.log_every_documents,
                        args.analysis_batch_size,
                        args.scratch_root,
                        args.max_document_bytes,
                        args.max_analysis_batch_bytes,
                        args.max_inflight_bytes,
                        int(args.scratch_min_free_gb * 1_000_000_000),
                        args.max_manifest_member_bytes,
                        args.max_manifest_line_bytes,
                    )
                except BaseException as exc:
                    record_error(staging_root, candidate, exc)
                    print(json.dumps({"event": "archive_error", "archive": candidate.relative_path, "error": str(exc)}, sort_keys=True), flush=True)
                    if args.fail_fast:
                        raise
                else:
                    print(
                        json.dumps({"event": "archive_complete", **report}, sort_keys=True),
                        flush=True,
                    )
                    if args.index_mode == "inline":
                        assert index is not None
                        # Index failures are not raw-archive failures: the
                        # checksummed report/fingerprint remain restart-safe.
                        result = index.ingest(
                            staging_root,
                            report,
                            batch_size=args.index_batch_size,
                        )
                        print(
                            json.dumps(
                                {
                                    "event": "dedup_ingested",
                                    "archive": report["archive"],
                                    **result,
                                },
                                sort_keys=True,
                            ),
                            flush=True,
                        )
                    else:
                        print(
                            json.dumps(
                                {"event": "dedup_deferred", "archive": report["archive"]},
                                sort_keys=True,
                            ),
                            flush=True,
                        )
                    maybe_write_status()
                processed_this_run += 1
                made_progress = True
                if stop_request.requested or (
                    args.max_archives is not None and processed_this_run >= args.max_archives
                ):
                    break
            terminal = args.once or stop_request.requested or (
                args.max_archives is not None and processed_this_run >= args.max_archives
            )
            snapshot = maybe_write_status(force=terminal)
            if snapshot is not None:
                print(
                    json.dumps({"event": "status", **snapshot}, sort_keys=True),
                    flush=True,
                )
            if terminal:
                failures = terminal_gate_failures(
                    snapshot,
                    require_index_complete=args.index_mode in ("inline", "only"),
                    require_closed_collection=args.require_closed_collection,
                )
                if terminal_operational_error is not None:
                    failures.append(terminal_operational_error)
                if failures:
                    print(
                        json.dumps(
                            {"event": "terminal_incomplete", "failures": failures},
                            sort_keys=True,
                        ),
                        flush=True,
                    )
                    return 2
                break
            if not made_progress:
                time.sleep(args.poll_seconds)
        return 0
    finally:
        if executor is not None:
            executor.shutdown(wait=True, cancel_futures=False)
        if index is not None:
            index.close()
        lock_handle.close()


if __name__ == "__main__":
    sys.exit(main())
