def reconcile_published_states(staging_root: Path) -> int:
    """Make a durable report authoritative over a legacy stale error marker.

    Older builds published the success report before unlinking an error left by
    a retry. A crash in that window could leave both files: discovery correctly
    skipped the completed report, but the stale error kept the terminal gate
    red forever. Reports are atomically written and therefore win this one
    unambiguous state. The current publisher removes the error first, so this is
    principally a one-time repair for an existing volume.
    """
    reports_root = staging_root / "reports"
    if not reports_root.exists():
        return 0
    reconciled = 0
    for published_report in sorted(reports_root.glob("*/*.json")):
        bucket = published_report.parent.name
        match = re.fullmatch(r"part-(\d{6})\.json", published_report.name)
        if bucket not in BUCKET_PATHS or match is None:
            continue
        stale_error = error_path(staging_root, bucket, int(match.group(1)))
        if durable_unlink(stale_error):
            reconciled += 1
    return reconciled


def load_quota_records(root: Path) -> dict[tuple[str, int], dict[str, Any]]:
    result: dict[tuple[str, int], dict[str, Any]] = {}
    directory = root / "state" / "quota_records" / "collection"
    for path in sorted(directory.glob("*.json")) if directory.exists() else []:
        record = json.loads(path.read_text(encoding="utf-8"))
        bucket = quota_record_bucket(record)
        if bucket is None:
            continue
        match = re.search(r"-(\d{6})$", str(record.get("shard_id") or ""))
        if not match:
            continue
        key = (bucket, int(match.group(1)))
        if key in result:
            raise RuntimeError(f"Duplicate quota records for {bucket} part {key[1]:06d}")
        result[key] = record
    return result


def quota_record_bucket(record: dict[str, Any]) -> str | None:
    category = record.get("category")
    language_group = record.get("language_group")
    if category == "python":
        return "python"
    if category == "other_code":
        return "other_code"
    if category == "english" and language_group in ("fineweb_edu", "wikipedia"):
        return str(language_group)
    return None


def _read_bounded_json_object(path: Path, *, label: str) -> tuple[bytes, dict[str, Any]]:
    """Read a small control-plane JSON file without following unsafe entries."""
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"Missing or unsafe {label}: {path}")
    size = path.stat().st_size
    if size <= 0 or size > MAX_CLOSURE_JSON_BYTES:
        raise ValueError(
            f"{label} has invalid size {size}; expected 1..{MAX_CLOSURE_JSON_BYTES} bytes: {path}"
        )
    raw = path.read_bytes()
    value = json.loads(raw)
    if not isinstance(value, dict):
        raise ValueError(f"{label} must be a JSON object: {path}")
    return raw, value


def _collection_targets_from_payload(
    payload: dict[str, Any], path: Path
) -> dict[str, int]:
    if payload.get("version") != 1 or not isinstance(payload.get("quotas"), list):
        raise ValueError(f"Unsupported quota configuration: {path}")
    targets: dict[str, int] = {}
    aggregate_english: int | None = None
    for row in payload["quotas"]:
        if not isinstance(row, dict):
            raise ValueError(f"Quota configuration row must be an object: {row!r}")
        if row.get("phase") != "collection":
            continue
        target = row.get("target")
        if (
            row.get("token_field") != "exact_tokens"
            or not isinstance(target, int)
            or isinstance(target, bool)
            or target <= 0
        ):
            raise ValueError(f"Invalid collection exact-token target: {row!r}")
        category = row.get("category")
        language_group = row.get("language_group")
        if category in ("python", "other_code") and language_group is None:
            bucket = str(category)
        elif category == "english" and language_group in ("fineweb_edu", "wikipedia"):
            bucket = str(language_group)
        elif category == "english" and language_group is None:
            if aggregate_english is not None:
                raise ValueError("Duplicate aggregate English collection target")
            aggregate_english = target
            continue
        else:
            raise ValueError(f"Invalid collection quota row: {row!r}")
        if bucket in targets:
            raise ValueError(f"Duplicate collection target for {bucket}")
        targets[bucket] = target
    if set(targets) != set(BUCKET_PATHS):
        raise ValueError(
            f"Collection targets must cover exactly {sorted(BUCKET_PATHS)}"
        )
    if aggregate_english is not None and aggregate_english != (
        targets["fineweb_edu"] + targets["wikipedia"]
    ):
        raise ValueError("Aggregate English target does not equal its source targets")
    return {bucket: targets[bucket] for bucket in sorted(BUCKET_PATHS)}


def load_collection_targets_for_gate(path: Path) -> dict[str, int]:
    """Load exactly the four source-bucket acquisition targets."""
    _raw, payload = _read_bounded_json_object(path, label="quota configuration")
    return _collection_targets_from_payload(payload, path)


def _quota_record_filename(record: dict[str, Any]) -> str:
    identity = "\0".join(
        str(record.get(key) or "")
        for key in ("phase", "split", "category", "language_group", "shard_id")
    )
    return hashlib.sha256(identity.encode("utf-8")).hexdigest() + ".json"


def collection_closure_payload(
    root: Path,
    quota_path: Path = DEFAULT_QUOTAS,
    staging_root: Path | None = None,
) -> dict[str, Any]:
    """Prove collectors published a complete, immutable four-bucket snapshot.

    ``raw_audit_complete`` intentionally describes coverage of the ledger that
    exists *now*. This separate proof prevents an empty or still-growing ledger
    from being mistaken for the final corpus in production.
    """
    failures: list[str] = []
    marker_evidence: list[dict[str, Any]] = []
    pending_raw: list[str] = []
    malformed_raw: list[str] = []
    unsafe_raw: list[str] = []
    missing_raw: list[str] = []
    extra_raw: list[str] = []
    quota_config_sha256: str | None = None
    try:
        quota_raw, quota_payload = _read_bounded_json_object(
            quota_path, label="quota configuration"
        )
        quota_config_sha256 = hashlib.sha256(quota_raw).hexdigest()
        targets = _collection_targets_from_payload(quota_payload, quota_path)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        targets = {}
        failures.append(str(exc))

    totals = {
        bucket: {"archives": 0, "documents": 0, "clean_bytes": 0, "exact_tokens": 0}
        for bucket in sorted(BUCKET_PATHS)
    }
    sources: dict[str, set[str]] = {bucket: set() for bucket in BUCKET_PATHS}
    records: dict[tuple[str, int], dict[str, Any]] = {}
    ledger_directory = root / "state" / "quota_records" / "collection"
    if ledger_directory.is_symlink() or not ledger_directory.is_dir():
        failures.append(f"Missing or unsafe finalized collection ledger: {ledger_directory}")
    else:
        try:
            ledger_entries = sorted(ledger_directory.iterdir())
        except OSError as exc:
            ledger_entries = []
            failures.append(f"Could not enumerate finalized collection ledger: {exc}")
        if not ledger_entries:
            failures.append(f"Finalized collection ledger is empty: {ledger_directory}")
        for path in ledger_entries:
            if path.name.startswith(".") or path.suffix != ".json":
                failures.append(f"Pending or unrecognized collection quota record: {path}")
                continue
            try:
                _raw, record = _read_bounded_json_object(
                    path, label="collection quota record"
                )
            except (OSError, ValueError, json.JSONDecodeError) as exc:
                failures.append(str(exc))
                continue
            if record.get("record_version") != 1 or record.get("phase") != "collection":
                failures.append(f"Invalid collection quota record identity: {path}")
                continue
            if path.name != _quota_record_filename(record):
                failures.append(f"Collection quota record is not at its canonical path: {path}")
                continue
            bucket = quota_record_bucket(record)
            shard_id = record.get("shard_id")
            match = QUOTA_SHARD_SUFFIX.search(shard_id) if isinstance(shard_id, str) else None
            if bucket not in BUCKET_PATHS or match is None:
                failures.append(f"Unrecognized collection quota identity: {path}")
                continue
            key = (bucket, int(match.group(1)))
            if key in records:
                failures.append(
                    f"Duplicate collection quota records for {bucket} part {key[1]:06d}"
                )
                continue
            source = record.get("source")
            if not isinstance(source, str) or not source:
                failures.append(f"Collection quota source is missing: {path}")
                continue
            counts: dict[str, int] = {}
            valid_counts = True
            for field in ("documents", "clean_bytes", "exact_tokens"):
                value = record.get(field)
                if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
                    failures.append(f"Invalid positive {field} in collection quota record: {path}")
                    valid_counts = False
                    break
                counts[field] = value
            if not valid_counts:
                continue
            records[key] = record
            sources[bucket].add(source)
            totals[bucket]["archives"] += 1
            for field in ("documents", "clean_bytes", "exact_tokens"):
                totals[bucket][field] += counts[field]

    present_buckets = {bucket for bucket, _index in records}
    if present_buckets != set(BUCKET_PATHS):
        failures.append(
            "Finalized collection ledger must contain every source bucket; "
            f"found {sorted(present_buckets)}"
        )
    source_values: dict[str, str | None] = {}
    for bucket in sorted(BUCKET_PATHS):
        values = sources[bucket]
        if len(values) != 1:
            failures.append(
                f"Collection ledger must have exactly one source for {bucket}; "
                f"found {sorted(values)}"
            )
            source_values[bucket] = None
        else:
            source_values[bucket] = next(iter(values))
        target = targets.get(bucket)
        if target is not None and totals[bucket]["exact_tokens"] < target:
            failures.append(
                f"Collection target not reached for {bucket}: "
                f"{totals[bucket]['exact_tokens']} < {target} exact tokens"
            )

    expected_raw = set(records)
    found_raw: set[tuple[str, int]] = set()
    for bucket, relative_directory in sorted(BUCKET_PATHS.items()):
        directory = root / "raw" / relative_directory
        if directory.is_symlink() or not directory.is_dir():
            failures.append(f"Missing or unsafe raw archive directory for {bucket}: {directory}")
            continue
        try:
            entries = sorted(directory.iterdir())
        except OSError as exc:
            failures.append(f"Could not enumerate raw archive directory {directory}: {exc}")
            continue
        for path in entries:
            relative = str(path.relative_to(root))
            if path.name.startswith(".part-"):
                pending_raw.append(relative)
                continue
            if not path.name.startswith("part-"):
                continue
            match = ARCHIVE_NAME.fullmatch(path.name)
            if match is None:
                malformed_raw.append(relative)
                continue
            try:
                unsafe = path.is_symlink() or not path.is_file() or path.stat().st_size <= 0
            except OSError:
                unsafe = True
            if unsafe:
                unsafe_raw.append(relative)
                continue
            found_raw.add((bucket, int(match.group(1))))
    for bucket, index in sorted(expected_raw - found_raw):
        missing_raw.append(f"{bucket}/part-{index:06d}.tar.zst")
    for bucket, index in sorted(found_raw - expected_raw):
        extra_raw.append(f"{bucket}/part-{index:06d}.tar.zst")
    if pending_raw:
        failures.append(f"Pending raw archive inputs remain ({len(pending_raw)})")
    if malformed_raw:
        failures.append(f"Malformed raw archive inputs remain ({len(malformed_raw)})")
    if unsafe_raw:
        failures.append(f"Unsafe or empty raw archive inputs remain ({len(unsafe_raw)})")
    if missing_raw:
        failures.append(f"Finalized quota records are missing raw archives ({len(missing_raw)})")
    if extra_raw:
        failures.append(f"Raw archives have no finalized quota record ({len(extra_raw)})")

    preprocess_identity: dict[str, Any] | None = None
    tokenizer_identity: dict[str, Any] | None = None
    for filename, buckets in COMPLETION_MARKERS:
        path = root / "state" / filename
        try:
            raw, marker = _read_bounded_json_object(
                path, label="collection completion marker"
            )
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            failures.append(str(exc))
            continue
        marker_failure_start = len(failures)
        expected_source = source_values.get(buckets[0])
        if marker.get("source") != expected_source:
            failures.append(f"Collection completion marker source mismatch: {path}")
        if len(buckets) == 2:
            if source_values.get(buckets[0]) != source_values.get(buckets[1]):
                failures.append(f"Code buckets do not share one completion-marker source: {path}")
            for bucket in buckets:
                field = f"{bucket}_tokens"
                value = marker.get(field)
                if (
                    not isinstance(value, int)
                    or isinstance(value, bool)
                    or value != totals[bucket]["exact_tokens"]
                ):
                    failures.append(f"Collection completion marker {field} mismatch: {path}")
            marker_targets = marker.get("targets")
            if marker_targets is not None and marker_targets != {
                bucket: targets.get(bucket) for bucket in buckets
            }:
                failures.append(f"Collection completion marker targets mismatch: {path}")
        else:
            bucket = buckets[0]
            value = marker.get("english_tokens")
            if (
                not isinstance(value, int)
                or isinstance(value, bool)
                or value != totals[bucket]["exact_tokens"]
            ):
                failures.append(f"Collection completion marker tokens mismatch: {path}")
            if marker.get("target") != targets.get(bucket):
                failures.append(f"Collection completion marker target mismatch: {path}")

        benchmark_identity = marker.get("benchmark_guard_sha256")
        if benchmark_identity is not None:
            if preprocess_identity is None:
                try:
                    _preprocess_raw, preprocess_identity = _read_bounded_json_object(
                        (staging_root or root / "staging" / "preprocess")
                        / "PREPROCESS_MANIFEST.json",
                        label="preprocess policy manifest",
                    )
                except (OSError, ValueError, json.JSONDecodeError) as exc:
                    failures.append(str(exc))
                    preprocess_identity = {}
            if benchmark_identity != preprocess_identity.get("benchmark_guard_sha256"):
                failures.append(f"Collection completion marker benchmark guard mismatch: {path}")
        tokenizer_revision = marker.get("tokenizer_revision")
        if tokenizer_revision is not None:
            if tokenizer_identity is None:
                try:
                    _tokenizer_raw, tokenizer_identity = _read_bounded_json_object(
                        root / "tokenizer" / "starcoder2" / "TOKENIZER_MANIFEST.json",
                        label="tokenizer manifest",
                    )
                except (OSError, ValueError, json.JSONDecodeError) as exc:
                    failures.append(str(exc))
                    tokenizer_identity = {}
            if tokenizer_revision != tokenizer_identity.get("resolved_revision"):
                failures.append(f"Collection completion marker tokenizer mismatch: {path}")
        marker_evidence.append(
            {
                "path": str(path.relative_to(root)),
                "sha256": hashlib.sha256(raw).hexdigest(),
                "buckets": list(buckets),
                "valid": len(failures) == marker_failure_start,
            }
        )

    valid_markers = sum(bool(item["valid"]) for item in marker_evidence)
    complete = not failures and valid_markers == len(COMPLETION_MARKERS)
    return {
        "closure_version": COLLECTION_CLOSURE_VERSION,
        "complete": complete,
        "quota_config_path": str(quota_path),
        "quota_config_sha256": quota_config_sha256,
        "targets": targets,
        "ledger": {
            "records": len(records),
            "per_bucket": totals,
            "sources": source_values,
        },
        "raw_inventory": {
            "expected_archives": len(expected_raw),
            "finalized_archives": len(found_raw),
            "pending_inputs": len(pending_raw),
            "malformed_inputs": len(malformed_raw),
            "unsafe_inputs": len(unsafe_raw),
            "missing_archives": len(missing_raw),
            "extra_archives": len(extra_raw),
            "samples": {
                "pending_inputs": pending_raw[:20],
                "malformed_inputs": malformed_raw[:20],
                "unsafe_inputs": unsafe_raw[:20],
                "missing_archives": missing_raw[:20],
                "extra_archives": extra_raw[:20],
            },
        },
        "completion_markers": {
            "required": len(COMPLETION_MARKERS),
            "present_and_readable": len(marker_evidence),
            "valid": valid_markers,
            "files": marker_evidence,
        },
        "failure_count": len(failures),
        "failures": failures[:100],
    }


def discover_archives(
    root: Path,
    staging_root: Path,
    retry_errors: bool = False,
) -> list[ArchiveCandidate]:
    quota_records = load_quota_records(root)
    candidates: list[ArchiveCandidate] = []
    for bucket, relative_directory in BUCKET_PATHS.items():
        directory = root / "raw" / relative_directory
        if not directory.exists():
            continue
        for path in sorted(directory.glob("part-*.tar.zst")):
            match = re.fullmatch(r"part-(\d{6})\.tar\.zst", path.name)
            if not match:
                continue
            index = int(match.group(1))
            quota_record = quota_records.get((bucket, index))
            if not quota_record:
                continue
            if report_path(staging_root, bucket, index).exists():
                continue
            if error_path(staging_root, bucket, index).exists() and not retry_errors:
                continue
            candidates.append(
                ArchiveCandidate(
                    bucket=bucket,
                    index=index,
                    path=path,
                    relative_path=str(path.relative_to(root)),
                    quota_record=quota_record,
                )
            )
    # Finishing small archives first produces useful audit/dedup results quickly
    # while a backlog exists. Eligibility and identities remain deterministic.
    return sorted(candidates, key=lambda item: (item.path.stat().st_size, item.bucket, item.index))


def provenance_fields(manifest: dict[str, Any]) -> dict[str, Any]:
    keys = (
        "repo_path",
        "repo_id",
        "commit_id",
        "file_path",
        "content_id",
        "language",
        "license_type",
        "detected_licenses",
        "id",
        "title",
        "url",
        "dump",
        "language_score",
        "fineweb_token_count",
        "fineweb_edu_score",
        "fineweb_edu_int_score",
    )
    return {key: manifest.get(key) for key in keys if manifest.get(key) is not None}


def stable_doc_id(candidate: ArchiveCandidate, member_path: str) -> str:
    identity = f"{candidate.relative_path}\0{member_path}"
    return hashlib.sha256(identity.encode("utf-8")).hexdigest()


def _write_metric_line(handle: Any, member_path: str, analysis: dict[str, Any]) -> None:
    handle.write(
        json.dumps(
            {"member_path": member_path, **analysis},
            ensure_ascii=False,
            separators=(",", ":"),
        )
        + "\n"
    )


def process_archive(
    candidate: ArchiveCandidate,
    staging_root: Path,
    executor: concurrent.futures.Executor | None,
    log_every_documents: int,
    analysis_batch_size: int = 64,
    scratch_root: Path | None = None,
    max_document_bytes: int = DEFAULT_MAX_DOCUMENT_BYTES,
    max_analysis_batch_bytes: int = DEFAULT_MAX_ANALYSIS_BATCH_BYTES,
    max_inflight_bytes: int = DEFAULT_MAX_INFLIGHT_BYTES,
    scratch_min_free_bytes: int = 0,
    max_manifest_member_bytes: int = DEFAULT_MAX_MANIFEST_MEMBER_BYTES,
    max_manifest_line_bytes: int = DEFAULT_MAX_MANIFEST_LINE_BYTES,
) -> dict[str, Any]:
    if analysis_batch_size < 1:
        raise ValueError("analysis_batch_size must be positive")
    if not (0 < max_document_bytes <= max_analysis_batch_bytes <= max_inflight_bytes):
        raise ValueError(
            "Memory caps must satisfy 0 < max_document_bytes <= "
            "max_analysis_batch_bytes <= max_inflight_bytes"
        )
    if scratch_min_free_bytes < 0:
        raise ValueError("scratch_min_free_bytes cannot be negative")
    if max_manifest_member_bytes < 1 or max_manifest_line_bytes < 1:
        raise ValueError("Internal-manifest byte caps must be positive")
    expected_documents = candidate.quota_record.get("documents")
    if (
        not isinstance(expected_documents, int)
        or isinstance(expected_documents, bool)
        or expected_documents <= 0
    ):
        raise ValueError("Quota record documents must be a positive integer")
    started = time.monotonic()
    staging_root.mkdir(parents=True, exist_ok=True)
    temporary_directory = scratch_root or staging_root / ".tmp"
    temporary_directory.mkdir(parents=True, exist_ok=True)
    require_free_space(temporary_directory, scratch_min_free_bytes, "scratch/spool")
    metrics_descriptor, metrics_name = tempfile.mkstemp(
        prefix=f".{candidate.bucket}-{candidate.index:06d}-metrics-",
        suffix=".jsonl",
        dir=temporary_directory,
    )
    os.close(metrics_descriptor)
    metrics_path = Path(metrics_name)
    output_path = fingerprint_path(staging_root, candidate.bucket, candidate.index)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_descriptor, output_name = tempfile.mkstemp(
        prefix=f".{output_path.name}.", dir=output_path.parent
    )
    os.close(output_descriptor)
    output_temporary = Path(output_name)
    archive_digest = hashlib.sha256()
    fingerprint_digest = hashlib.sha256()
    documents_read = 0
    manifest_seen = False
    pending: collections.deque[
        tuple[list[str], int, concurrent.futures.Future[list[dict[str, Any]]]]
    ] = collections.deque()
    batch_member_paths: list[str] = []
    batch_contents: list[bytes] = []
    batch_bytes = 0
    pending_bytes = 0
    peak_inflight_bytes = 0
    peak_batch_bytes = 0
    submitted_batches = 0
    last_scratch_check = time.monotonic()
    max_pending = 1 if executor is None else max(2, getattr(executor, "_max_workers", 1) * 2)

    def observe_memory() -> None:
        nonlocal peak_inflight_bytes, peak_batch_bytes
        peak_batch_bytes = max(peak_batch_bytes, batch_bytes)
        peak_inflight_bytes = max(peak_inflight_bytes, pending_bytes + batch_bytes)

    def maybe_check_scratch(*, force: bool = False) -> None:
        nonlocal last_scratch_check
        now = time.monotonic()
        if force or now - last_scratch_check >= SCRATCH_RECHECK_SECONDS:
            require_free_space(temporary_directory, scratch_min_free_bytes, "scratch/spool")
            last_scratch_check = now

    def drain_one(metrics_handle: Any) -> None:
        nonlocal pending_bytes
        member_paths, payload_bytes, future = pending.popleft()
        try:
            analyses = future.result()
        finally:
            pending_bytes -= payload_bytes
        if len(member_paths) != len(analyses):
            raise RuntimeError("Analysis worker returned a different batch length")
        for member_path, analysis in zip(member_paths, analyses, strict=True):
            _write_metric_line(metrics_handle, member_path, analysis)
        maybe_check_scratch()

    def submit_batch(metrics_handle: Any) -> None:
        nonlocal batch_member_paths, batch_contents, batch_bytes, pending_bytes
        nonlocal submitted_batches
        if not batch_contents:
            return
        while pending and pending_bytes + batch_bytes > max_inflight_bytes:
            drain_one(metrics_handle)
        if pending_bytes + batch_bytes > max_inflight_bytes:
            raise RuntimeError("Internal in-flight byte accounting exceeded its cap")
        payload_bytes = batch_bytes
        if executor is None:
            future: concurrent.futures.Future[list[dict[str, Any]]] = (
                concurrent.futures.Future()
            )
            future.set_result(analyze_document_batch(batch_contents, candidate.bucket))
        else:
            future = executor.submit(
                analyze_document_batch,
                batch_contents,
                candidate.bucket,
            )
        pending.append((batch_member_paths, payload_bytes, future))
        pending_bytes += payload_bytes
        submitted_batches += 1
        batch_member_paths = []
        batch_contents = []
        batch_bytes = 0
        observe_memory()
        if len(pending) >= max_pending:
            drain_one(metrics_handle)

    def make_room_for_document(metrics_handle: Any, document_bytes: int) -> None:
        if batch_contents and (
            len(batch_contents) >= analysis_batch_size
            or batch_bytes + document_bytes > max_analysis_batch_bytes
        ):
            submit_batch(metrics_handle)
        while pending and pending_bytes + batch_bytes + document_bytes > max_inflight_bytes:
            drain_one(metrics_handle)
        if batch_bytes + document_bytes > max_analysis_batch_bytes:
            raise RuntimeError("Internal analysis batch byte accounting exceeded its cap")
        if pending_bytes + batch_bytes + document_bytes > max_inflight_bytes:
            raise RuntimeError("Internal in-flight byte accounting exceeded its cap")

    def settle_abandoned_work() -> None:
        """Do not let failed-archive payloads escape accounting into the next one."""
        nonlocal pending_bytes
        abandoned = list(pending)
        pending.clear()
        pending_bytes = 0
        for _member_paths, _payload_bytes, future in abandoned:
            future.cancel()
        for _member_paths, _payload_bytes, future in abandoned:
            if future.cancelled():
                continue
            try:
                future.result()
            except BaseException:
                # The primary archive failure remains authoritative. This wait
                # only guarantees the shared executor has released its inputs.
                pass

    try:
        with metrics_path.open("w+", encoding="utf-8") as metrics_handle:
            with candidate.path.open("rb") as raw_archive:
                hashing_reader = HashingReader(raw_archive, archive_digest)
                decompressor = zstandard.ZstdDecompressor().stream_reader(
                    hashing_reader, read_across_frames=True, closefd=False
                )
                try:
                    with tarfile.open(fileobj=decompressor, mode="r|") as archive:
                        for member in archive:
                            if not member.isfile():
                                raise ValueError(f"Unexpected non-file tar member: {member.name}")
                            if (
                                member.name == "_manifest.jsonl"
                                and member.size > max_manifest_member_bytes
                            ):
                                # The manifest is streamed, but an absurd declared
                                # member would otherwise permit unbounded work and
                                # output before the row-count check can fire.
                                raise ManifestSafetyError(
                                    limit="member_bytes",
                                    observed=int(member.size),
                                    maximum=max_manifest_member_bytes,
                                )
                            if member.name != "_manifest.jsonl" and member.size > max_document_bytes:
                                # Do not call extractfile/read: the declared size is
                                # already outside the reviewed operational envelope.
                                # The whole archive remains unpublished and receives
                                # a durable, typed quarantine/error record in main.
                                raise OversizeDocumentError(
                                    member.name,
                                    int(member.size),
                                    max_document_bytes,
                                )
                            extracted = archive.extractfile(member)
                            if extracted is None:
                                raise ValueError(f"Could not read tar member: {member.name}")
                            if member.name == "_manifest.jsonl":
                                if manifest_seen:
                                    raise ValueError("Archive contains multiple internal manifests")
                                manifest_seen = True
                                submit_batch(metrics_handle)
                                while pending:
                                    drain_one(metrics_handle)
                                metrics_handle.flush()
                                metrics_handle.seek(0)
                                report = join_manifest_and_metrics(
                                    candidate,
                                    extracted,
                                    metrics_handle,
                                    output_temporary,
                                    fingerprint_digest,
                                    expected_documents=expected_documents,
                                    max_manifest_line_bytes=max_manifest_line_bytes,
                                )
                            else:
                                if manifest_seen:
                                    raise ValueError("Document member appears after internal manifest")
                                if documents_read >= expected_documents:
                                    raise ManifestSafetyError(
                                        limit="document_rows",
                                        observed=documents_read + 1,
                                        maximum=expected_documents,
                                        row_index=documents_read,
                                    )
                                make_room_for_document(metrics_handle, int(member.size))
                                # A bounded read protects against both accidental
                                # giant members and malformed streams whose payload
                                # disagrees with the tar header.
                                content = extracted.read(max_document_bytes + 1)
                                if len(content) > max_document_bytes:
                                    raise OversizeDocumentError(
                                        member.name,
                                        len(content),
                                        max_document_bytes,
                                    )
                                if len(content) != member.size:
                                    raise ValueError(
                                        f"Tar member size mismatch for {member.name}: "
                                        f"{len(content)} != {member.size}"
                                )
                                batch_member_paths.append(member.name)
                                batch_contents.append(content)
                                batch_bytes += len(content)
                                observe_memory()
                                documents_read += 1
                                if (
                                    len(batch_contents) >= analysis_batch_size
                                    or batch_bytes >= max_analysis_batch_bytes
                                ):
                                    submit_batch(metrics_handle)
                                if documents_read % log_every_documents == 0:
                                    maybe_check_scratch(force=True)
                                    print(
                                        json.dumps(
                                            {
                                                "event": "archive_progress",
                                                "archive": candidate.relative_path,
                                                "documents_read": documents_read,
                                                "inflight_payload_bytes": pending_bytes
                                                + batch_bytes,
                                            },
                                            sort_keys=True,
                                        ),
                                        flush=True,
                                    )
                    while decompressor.read(8 * 1024 * 1024):
                        pass
                finally:
                    decompressor.close()
                while hashing_reader.read(8 * 1024 * 1024):
                    pass
        if not manifest_seen:
            raise ValueError("Archive is missing _manifest.jsonl")
        if int(report["documents"]) != documents_read:
            raise ValueError(
                f"Document count mismatch: manifest {report['documents']} != tar {documents_read}"
            )
        expected = candidate.quota_record
        for report_key, quota_key in (
            ("documents", "documents"),
            ("clean_bytes", "clean_bytes"),
            ("exact_tokens", "exact_tokens"),
        ):
            if int(report[report_key]) != int(expected.get(quota_key) or 0):
                raise ValueError(
                    f"Quota mismatch for {report_key}: {report[report_key]} != {expected.get(quota_key)}"
                )
        os.replace(output_temporary, output_path)
        fsync_directory(output_path.parent)
        elapsed = max(time.monotonic() - started, 1e-9)
        complete_report = {
            "report_version": 1,
            "fingerprint_version": FINGERPRINT_VERSION,
            "policy_sha256": POLICY_SHA256,
            "archive": candidate.relative_path,
            "archive_sha256": archive_digest.hexdigest(),
            "archive_compressed_bytes": candidate.path.stat().st_size,
            "bucket": candidate.bucket,
            "index": candidate.index,
            "quota_shard_id": candidate.quota_record.get("shard_id"),
            "source": candidate.quota_record.get("source"),
            "fingerprint_file": str(output_path.relative_to(staging_root)),
            "fingerprint_sha256": fingerprint_digest.hexdigest(),
            "elapsed_seconds": round(elapsed, 3),
            "compressed_MB_per_second": round(candidate.path.stat().st_size / elapsed / 1_000_000, 3),
            "operational_memory": {
                "max_document_bytes": max_document_bytes,
                "max_analysis_batch_bytes": max_analysis_batch_bytes,
                "max_inflight_bytes": max_inflight_bytes,
                "manifest_safety_version": MANIFEST_SAFETY_VERSION,
                "max_manifest_member_bytes": max_manifest_member_bytes,
                "max_manifest_line_bytes": max_manifest_line_bytes,
                "max_manifest_rows": expected_documents,
                "peak_analysis_batch_bytes": peak_batch_bytes,
                "peak_inflight_payload_bytes": peak_inflight_bytes,
                "submitted_batches": submitted_batches,
                "oversize_documents": 0,
            },
            **report,
        }
        # Success publication is a tiny transaction. Remove and fsync any old
        # error first; a crash before the atomic report then leaves the archive
        # rediscoverable. Once the durable report exists there can be no stale
        # error marker to wedge the completion gate.
        durable_unlink(error_path(staging_root, candidate.bucket, candidate.index))
        atomic_json(report_path(staging_root, candidate.bucket, candidate.index), complete_report)
        return complete_report
    finally:
        settle_abandoned_work()
        for temporary in (metrics_path, output_temporary):
            try:
                temporary.unlink()
            except FileNotFoundError:
                pass


def join_manifest_and_metrics(
    candidate: ArchiveCandidate,
    manifest_handle: BinaryIO,
    metrics_handle: Any,
    output_temporary: Path,
    fingerprint_digest: Any,
    *,
    expected_documents: int,
    max_manifest_line_bytes: int,
) -> dict[str, Any]:
    documents = 0
    clean_bytes = 0
    exact_tokens = 0
    benchmark_hits = 0
    flag_counts: collections.Counter[str] = collections.Counter()
    language_documents: collections.Counter[str] = collections.Counter()
    language_tokens: collections.Counter[str] = collections.Counter()
    raw_output = output_temporary.open("wb")
    compressor = zstandard.ZstdCompressor(level=3, threads=1, write_checksum=True)
    hashing_output = HashingWriter(raw_output, fingerprint_digest)
    compressed = compressor.stream_writer(hashing_output, closefd=False)
    try:
        for manifest_index in range(expected_documents + 1):
            raw_manifest_line = manifest_handle.readline(max_manifest_line_bytes + 1)
            if not raw_manifest_line:
                break
            if len(raw_manifest_line) > max_manifest_line_bytes:
                raise ManifestSafetyError(
                    limit="line_bytes",
                    observed=len(raw_manifest_line),
                    maximum=max_manifest_line_bytes,
                    row_index=manifest_index,
                )
            if manifest_index >= expected_documents:
                # Read one bounded row beyond the quota count, but reject it
                # before JSON decoding or provenance materialization.
                raise ManifestSafetyError(
                    limit="manifest_rows",
                    observed=manifest_index + 1,
                    maximum=expected_documents,
                    row_index=manifest_index,
                )
            manifest = json.loads(raw_manifest_line)
            metric_line = metrics_handle.readline()
            if not metric_line:
                raise ValueError("Internal manifest has more rows than document members")
            metric = json.loads(metric_line)
            member_path = str(manifest.get("member_path") or "")
            if member_path != metric.get("member_path"):
                raise ValueError(
                    f"Member order mismatch at row {manifest_index}: "
                    f"{member_path!r} != {metric.get('member_path')!r}"
                )
            size_bytes = int(manifest.get("size_bytes") or 0)
            token_count = int(manifest.get("starcoder2_tokens") or 0)
            if size_bytes != int(metric["size_bytes"]):
                raise ValueError(f"Manifest byte count mismatch for {member_path}")
            if size_bytes <= 0 or token_count <= 0:
                raise ValueError(f"Non-positive size/token count for {member_path}")
            language = str(manifest.get("language") or candidate.bucket)
            row = {
                "record_version": 1,
                "fingerprint_version": FINGERPRINT_VERSION,
                "doc_id": stable_doc_id(candidate, member_path),
                "bucket": candidate.bucket,
                "archive": candidate.relative_path,
                "archive_index": candidate.index,
                "manifest_index": manifest_index,
                "member_path": member_path,
                "size_bytes": size_bytes,
                "starcoder2_tokens": token_count,
                "content_sha256": metric["content_sha256"],
                "normalized_sha256": metric["normalized_sha256"],
                "near_sketch": metric["near_sketch"],
                "metrics": metric["metrics"],
                "quality_flags": metric["quality_flags"],
                "benchmark_reason": metric["benchmark_reason"],
                "provenance": provenance_fields(manifest),
            }
            compressed.write(
                (json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n").encode(
                    "utf-8"
                )
            )
            documents += 1
            clean_bytes += size_bytes
            exact_tokens += token_count
            language_documents[language] += 1
            language_tokens[language] += token_count
            if metric["benchmark_reason"]:
                benchmark_hits += 1
            flag_counts.update(metric["quality_flags"])
        if metrics_handle.readline():
            raise ValueError("Archive has more document members than internal manifest rows")
        compressed.flush(zstandard.FLUSH_FRAME)
        compressed.close()
        raw_output.flush()
        os.fsync(raw_output.fileno())
    finally:
        try:
            compressed.close()
        except Exception:
            pass
        raw_output.close()
    return {
        "documents": documents,
        "clean_bytes": clean_bytes,
        "exact_tokens": exact_tokens,
        "benchmark_hits": benchmark_hits,
        "quality_flag_counts": dict(sorted(flag_counts.items())),
        "language_documents": dict(sorted(language_documents.items())),
        "language_tokens": dict(sorted(language_tokens.items())),
    }


class DedupIndex:
    def __init__(self, path: Path):
        path.parent.mkdir(parents=True, exist_ok=True)
        self.path = path
        self.connection = sqlite3.connect(path, timeout=120)
        self.connection.execute("PRAGMA journal_mode=DELETE")
        self.connection.execute("PRAGMA synchronous=FULL")
        self.connection.execute("PRAGMA temp_store=MEMORY")
        self.connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS metadata (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL
            ) WITHOUT ROWID;
            CREATE TABLE IF NOT EXISTS documents (
                doc_id TEXT PRIMARY KEY,
                bucket TEXT NOT NULL,
                archive TEXT NOT NULL,
                member_path TEXT NOT NULL,
                content_hash BLOB NOT NULL,
                normalized_hash BLOB NOT NULL,
                tokens INTEGER NOT NULL,
                quality_flags TEXT NOT NULL,
                benchmark_reason TEXT
            ) WITHOUT ROWID;
            CREATE TABLE IF NOT EXISTS exact_clusters (
                hash BLOB PRIMARY KEY,
                first_doc_id TEXT NOT NULL,
                documents INTEGER NOT NULL,
                tokens INTEGER NOT NULL
            ) WITHOUT ROWID;
            CREATE TABLE IF NOT EXISTS normalized_clusters (
                hash BLOB PRIMARY KEY,
                first_doc_id TEXT NOT NULL,
                documents INTEGER NOT NULL,
                tokens INTEGER NOT NULL
            ) WITHOUT ROWID;
            CREATE TABLE IF NOT EXISTS ingested_archives (
                archive TEXT PRIMARY KEY,
                fingerprint_sha256 TEXT NOT NULL,
                documents INTEGER NOT NULL,
                tokens INTEGER NOT NULL,
                exact_duplicate_documents INTEGER NOT NULL,
                normalized_duplicate_documents INTEGER NOT NULL,
                ingested_at TEXT NOT NULL
            ) WITHOUT ROWID;
            """
        )
        # Per-archive staging tables let SQLite perform cluster joins and
        # upserts in bulk. They live only for this connection and are cleared
        # before every transaction, so they are safe across retries.
        self.connection.executescript(
            """
            CREATE TEMP TABLE IF NOT EXISTS archive_exact_groups (
                hash BLOB PRIMARY KEY,
                first_doc_id TEXT NOT NULL,
                documents INTEGER NOT NULL,
                tokens INTEGER NOT NULL
            ) WITHOUT ROWID;
            CREATE TEMP TABLE IF NOT EXISTS archive_normalized_groups (
                hash BLOB PRIMARY KEY,
                first_doc_id TEXT NOT NULL,
                documents INTEGER NOT NULL,
                tokens INTEGER NOT NULL
            ) WITHOUT ROWID;
            """
        )
        ingested_columns = {
            str(row[1])
            for row in self.connection.execute("PRAGMA table_info(ingested_archives)")
        }
        if "tokens" not in ingested_columns:
            self.connection.execute("ALTER TABLE ingested_archives ADD COLUMN tokens INTEGER")
        self._set_or_validate_metadata("database_version", str(DATABASE_VERSION))
        self._set_or_validate_metadata("policy_sha256", POLICY_SHA256)
        self.connection.commit()

    def _set_or_validate_metadata(self, key: str, value: str) -> None:
        row = self.connection.execute("SELECT value FROM metadata WHERE key = ?", (key,)).fetchone()
        if row and row[0] != value:
            raise RuntimeError(f"Dedup database {key} mismatch: {row[0]} != {value}")
        self.connection.execute("INSERT OR IGNORE INTO metadata(key, value) VALUES (?, ?)", (key, value))

    def close(self) -> None:
        self.connection.close()

    def has_archive(self, archive: str) -> bool:
        return self.connection.execute(
            "SELECT 1 FROM ingested_archives WHERE archive = ?", (archive,)
        ).fetchone() is not None

    def validate_ingested_report(self, report: dict[str, Any]) -> bool:
        archive = str(report["archive"])
        row = self.connection.execute(
            """
            SELECT fingerprint_sha256, documents, tokens
            FROM ingested_archives
            WHERE archive = ?
            """,
            (archive,),
        ).fetchone()
        if row is None:
            return False
        expected = (
            str(report["fingerprint_sha256"]),
            int(report["documents"]),
            int(report["exact_tokens"]),
        )
        actual = (str(row[0]), int(row[1]), int(row[2]))
        if actual != expected:
            raise RuntimeError(
                f"Indexed archive summary mismatch for {archive}: {actual} != {expected}"
            )
        return True

    def ingest(
        self,
        staging_root: Path,
        report: dict[str, Any],
        *,
        batch_size: int = DEFAULT_INDEX_BATCH_SIZE,
    ) -> dict[str, int]:
        archive = str(report["archive"])
        if self.validate_ingested_report(report):
            return {"documents": 0, "exact_duplicate_documents": 0, "normalized_duplicate_documents": 0}
        if batch_size < 1:
            raise ValueError("Dedup index batch_size must be positive")
        fingerprints = staging_root / str(report["fingerprint_file"])
        if file_sha256(fingerprints) != report["fingerprint_sha256"]:
            raise RuntimeError(f"Fingerprint checksum mismatch: {fingerprints}")
        documents = 0
        fingerprint_tokens = 0
        document_batch: list[tuple[Any, ...]] = []
        exact_groups: dict[bytes, list[Any]] = {}
        normalized_groups: dict[bytes, list[Any]] = {}

        def add_group(
            groups: dict[bytes, list[Any]],
            digest: bytes,
            doc_id: str,
            tokens: int,
        ) -> None:
            group = groups.get(digest)
            if group is None:
                groups[digest] = [doc_id, 1, tokens]
                return
            if doc_id < group[0]:
                group[0] = doc_id
            group[1] += 1
            group[2] += tokens

        def flush_documents() -> None:
            if not document_batch:
                return
            # doc_id includes the immutable archive/member identity, so a
            # collision is corruption and must fail instead of being ignored.
            self.connection.executemany(
                """
                INSERT INTO documents(
                    doc_id, bucket, archive, member_path, content_hash,
                    normalized_hash, tokens, quality_flags, benchmark_reason
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                document_batch,
            )
            document_batch.clear()

        self.connection.execute("BEGIN IMMEDIATE")
        try:
            self.connection.execute("DELETE FROM archive_exact_groups")
            self.connection.execute("DELETE FROM archive_normalized_groups")
            with fingerprints.open("rb") as raw:
                with zstandard.ZstdDecompressor().stream_reader(raw) as stream:
                    with io.TextIOWrapper(stream, encoding="utf-8") as text_stream:
                        for line in text_stream:
                            row = json.loads(line)
                            if str(row["archive"]) != archive:
                                raise RuntimeError(
                                    f"Fingerprint archive mismatch for {archive}: {row['archive']}"
                                )
                            if str(row["bucket"]) != str(report["bucket"]):
                                raise RuntimeError(
                                    f"Fingerprint bucket mismatch for {archive}: {row['bucket']}"
                                )
                            doc_id = str(row["doc_id"])
                            tokens = int(row["starcoder2_tokens"])
                            if tokens <= 0:
                                raise RuntimeError(
                                    f"Fingerprint has non-positive tokens for {doc_id}"
                                )
                            try:
                                exact_hash = bytes.fromhex(row["content_sha256"])
                                normalized_hash = bytes.fromhex(row["normalized_sha256"])
                            except (TypeError, ValueError) as exc:
                                raise RuntimeError(
                                    f"Fingerprint has an invalid digest for {doc_id}"
                                ) from exc
                            if len(exact_hash) != 32 or len(normalized_hash) != 32:
                                raise RuntimeError(
                                    f"Fingerprint has a non-SHA256 digest for {doc_id}"
                                )
                            document_batch.append(
                                (
                                    doc_id,
                                    row["bucket"],
                                    row["archive"],
                                    row["member_path"],
                                    exact_hash,
                                    normalized_hash,
                                    tokens,
                                    json.dumps(row["quality_flags"], separators=(",", ":")),
                                    row.get("benchmark_reason"),
                                )
                            )
                            documents += 1
                            fingerprint_tokens += tokens
                            add_group(exact_groups, exact_hash, doc_id, tokens)
                            add_group(normalized_groups, normalized_hash, doc_id, tokens)
                            if len(document_batch) >= batch_size:
                                flush_documents()
            flush_documents()
            if documents != int(report["documents"]):
                raise RuntimeError(
                    f"Fingerprint document count mismatch for {archive}: {documents} != {report['documents']}"
                )
            if fingerprint_tokens != int(report["exact_tokens"]):
                raise RuntimeError(
                    f"Fingerprint token count mismatch for {archive}: "
                    f"{fingerprint_tokens} != {report['exact_tokens']}"
                )
            self.connection.executemany(
                "INSERT INTO archive_exact_groups(hash, first_doc_id, documents, tokens) VALUES (?, ?, ?, ?)",
                (
                    (digest, values[0], values[1], values[2])
                    for digest, values in exact_groups.items()
                ),
            )
            self.connection.executemany(
                "INSERT INTO archive_normalized_groups(hash, first_doc_id, documents, tokens) VALUES (?, ?, ?, ?)",
                (
                    (digest, values[0], values[1], values[2])
                    for digest, values in normalized_groups.items()
                ),
            )
            new_exact_clusters = int(
                self.connection.execute(
                    """
                    SELECT COUNT(*)
                    FROM archive_exact_groups AS incoming
                    LEFT JOIN exact_clusters AS existing USING(hash)
                    WHERE existing.hash IS NULL
                    """
                ).fetchone()[0]
            )
            new_normalized_clusters = int(
                self.connection.execute(
                    """
                    SELECT COUNT(*)
                    FROM archive_normalized_groups AS incoming
                    LEFT JOIN normalized_clusters AS existing USING(hash)
                    WHERE existing.hash IS NULL
                    """
                ).fetchone()[0]
            )
            exact_duplicates = documents - new_exact_clusters
            normalized_duplicates = documents - new_normalized_clusters
            self.connection.execute(
                """
                INSERT INTO exact_clusters(hash, first_doc_id, documents, tokens)
                SELECT hash, first_doc_id, documents, tokens
                FROM archive_exact_groups
                WHERE 1
                ON CONFLICT(hash) DO UPDATE SET
                    first_doc_id = MIN(exact_clusters.first_doc_id, excluded.first_doc_id),
                    documents = exact_clusters.documents + excluded.documents,
                    tokens = exact_clusters.tokens + excluded.tokens
                """
            )
            self.connection.execute(
                """
                INSERT INTO normalized_clusters(hash, first_doc_id, documents, tokens)
                SELECT hash, first_doc_id, documents, tokens
                FROM archive_normalized_groups
                WHERE 1
                ON CONFLICT(hash) DO UPDATE SET
                    first_doc_id = MIN(normalized_clusters.first_doc_id, excluded.first_doc_id),
                    documents = normalized_clusters.documents + excluded.documents,
                    tokens = normalized_clusters.tokens + excluded.tokens
                """
            )
            self.connection.execute(
                """
                INSERT INTO ingested_archives(
                    archive, fingerprint_sha256, documents, tokens,
                    exact_duplicate_documents, normalized_duplicate_documents, ingested_at
                ) VALUES (?, ?, ?, ?, ?, ?, datetime('now'))
                """,
                (
                    archive,
                    report["fingerprint_sha256"],
                    documents,
                    int(report["exact_tokens"]),
                    exact_duplicates,
                    normalized_duplicates,
                ),
            )
            self.connection.commit()
        except BaseException:
            self.connection.rollback()
            raise
        return {
            "documents": documents,
            "exact_duplicate_documents": exact_duplicates,
            "normalized_duplicate_documents": normalized_duplicates,
        }

    def backfill_archive_tokens(self, reports: Iterable[dict[str, Any]]) -> None:
        """Populate the summary column added to pre-existing dedup databases."""
        missing = {
            str(row[0])
            for row in self.connection.execute(
                "SELECT archive FROM ingested_archives WHERE tokens IS NULL"
            )
        }
        if not missing:
            return
        tokens_by_archive = {
            str(report["archive"]): int(report["exact_tokens"])
            for report in reports
            if str(report["archive"]) in missing
        }
        unresolved = missing - tokens_by_archive.keys()
        if unresolved:
            sample = ", ".join(sorted(unresolved)[:3])
            raise RuntimeError(
                f"Cannot migrate dedup token summaries; reports are missing for: {sample}"
            )
        self.connection.execute("BEGIN IMMEDIATE")
        try:
            self.connection.executemany(
                "UPDATE ingested_archives SET tokens = ? WHERE archive = ? AND tokens IS NULL",
                [
                    (tokens_by_archive[archive], archive)
                    for archive in sorted(missing)
                ],
            )
            self.connection.commit()
        except BaseException:
            self.connection.rollback()
            raise

    def status(self) -> dict[str, Any]:
        row = self.connection.execute(
            """
            SELECT
                COUNT(*),
                COALESCE(SUM(documents), 0),
                COALESCE(SUM(tokens), 0),
                COALESCE(SUM(exact_duplicate_documents), 0),
                COALESCE(SUM(normalized_duplicate_documents), 0)
            FROM ingested_archives
            """
        ).fetchone()
        ingested_archives = int(row[0])
        documents = int(row[1])
        tokens = int(row[2])
        exact_duplicate_documents = int(row[3])
        normalized_duplicate_documents = int(row[4])
        exact_clusters = documents - exact_duplicate_documents
        normalized_clusters = documents - normalized_duplicate_documents
        return {
            "ingested_archives": ingested_archives,
            "documents": documents,
            "tokens": tokens,
            "exact_clusters": exact_clusters,
            "exact_duplicate_documents": exact_duplicate_documents,
            "normalized_clusters": normalized_clusters,
            "normalized_duplicate_documents": normalized_duplicate_documents,
            "database_bytes": self.path.stat().st_size if self.path.exists() else 0,
        }


def iter_reports(staging_root: Path) -> Iterator[dict[str, Any]]:
    directory = staging_root / "reports"
    if not directory.exists():
        return
    for path in sorted(directory.glob("*/*.json")):
        yield json.loads(path.read_text(encoding="utf-8"))


def report_coverage_payload(root: Path, staging_root: Path) -> dict[str, Any]:
    """Prove a one-to-one report/fingerprint mapping for every quota archive."""
    quota_records = load_quota_records(root)
    expected_keys = set(quota_records)
    raw_keys: set[tuple[str, int]] = set()
    for bucket, relative_directory in BUCKET_PATHS.items():
        directory = root / "raw" / relative_directory
        for archive in sorted(directory.glob("part-*.tar.zst")) if directory.exists() else []:
            match = re.fullmatch(r"part-(\d{6})\.tar\.zst", archive.name)
            if match is not None:
                raw_keys.add((bucket, int(match.group(1))))

    report_keys: set[tuple[str, int]] = set()
    valid_keys: set[tuple[str, int]] = set()
    invalid_reports: list[str] = []
    reports_root = staging_root / "reports"
    report_files = sorted(reports_root.glob("*/*.json")) if reports_root.exists() else []
    for path in report_files:
        bucket = path.parent.name
        match = re.fullmatch(r"part-(\d{6})\.json", path.name)
        if bucket not in BUCKET_PATHS or match is None:
            invalid_reports.append(f"unexpected report path: {path.relative_to(staging_root)}")
            continue
        key = (bucket, int(match.group(1)))
        if key in report_keys:
            invalid_reports.append(f"duplicate report identity: {bucket}/{key[1]:06d}")
            continue
        report_keys.add(key)
        quota = quota_records.get(key)
        try:
            report = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            invalid_reports.append(f"unreadable report {path.relative_to(staging_root)}: {exc}")
            continue
        expected_archive = str(
            (root / "raw" / BUCKET_PATHS[bucket] / f"part-{key[1]:06d}.tar.zst")
            .relative_to(root)
        )
        expected_fingerprint = str(
            fingerprint_path(staging_root, bucket, key[1]).relative_to(staging_root)
        )
        raw_archive = root / expected_archive
        failures: list[str] = []
        if quota is None:
            failures.append("no matching quota record")
        else:
            expected_fields = {
                "report_version": 1,
                "fingerprint_version": FINGERPRINT_VERSION,
                "policy_sha256": POLICY_SHA256,
                "bucket": bucket,
                "index": key[1],
                "archive": expected_archive,
                "archive_compressed_bytes": raw_archive.stat().st_size
                if raw_archive.is_file()
                else None,
                "quota_shard_id": quota.get("shard_id"),
                "source": quota.get("source"),
                "documents": int(quota.get("documents") or 0),
                "clean_bytes": int(quota.get("clean_bytes") or 0),
                "exact_tokens": int(quota.get("exact_tokens") or 0),
                "fingerprint_file": expected_fingerprint,
            }
            for field, expected in expected_fields.items():
                if report.get(field) != expected:
                    failures.append(
                        f"{field}={report.get(field)!r}, expected {expected!r}"
                    )
        for digest_field in ("archive_sha256", "fingerprint_sha256"):
            value = report.get(digest_field)
            if (
                not isinstance(value, str)
                or len(value) != 64
                or any(character not in "0123456789abcdef" for character in value)
            ):
                failures.append(f"invalid {digest_field}")
        fingerprint = fingerprint_path(staging_root, bucket, key[1])
        if (
            not fingerprint.is_file()
            or fingerprint.is_symlink()
            or fingerprint.stat().st_size <= 0
        ):
            failures.append(f"missing/non-regular fingerprint {expected_fingerprint}")
        if key not in raw_keys:
            failures.append("finalized raw archive is missing")
        if failures:
            invalid_reports.append(
                f"{path.relative_to(staging_root)}: " + "; ".join(failures)
            )
        else:
            valid_keys.add(key)

    missing_reports = expected_keys - report_keys
    unexpected_reports = report_keys - expected_keys
    raw_without_quota = raw_keys - expected_keys
    quota_without_raw = expected_keys - raw_keys
    complete = not (
        missing_reports
        or unexpected_reports
        or raw_without_quota
        or quota_without_raw
        or invalid_reports
    ) and valid_keys == expected_keys

    def samples(keys: set[tuple[str, int]]) -> list[str]:
        return [f"{bucket}/part-{index:06d}" for bucket, index in sorted(keys)[:20]]

    return {
        "complete": complete,
        "expected_archives": len(expected_keys),
        "raw_archives": len(raw_keys),
        "report_files": len(report_files),
        "valid_reports": len(valid_keys),
        "missing_reports": len(missing_reports),
        "unexpected_reports": len(unexpected_reports),
        "invalid_reports": len(invalid_reports),
        "raw_archives_without_quota": len(raw_without_quota),
        "quota_records_without_raw_archive": len(quota_without_raw),
        "samples": {
            "missing_reports": samples(missing_reports),
            "unexpected_reports": samples(unexpected_reports),
            "raw_archives_without_quota": samples(raw_without_quota),
            "quota_records_without_raw_archive": samples(quota_without_raw),
            "invalid_reports": invalid_reports[:20],
        },
    }


def ensure_policy_manifest(staging_root: Path, denylist: Path) -> None:
    guard = BenchmarkGuard(denylist)
    path = staging_root / "PREPROCESS_MANIFEST.json"
    payload = {
        "manifest_version": 1,
        "fingerprint_version": FINGERPRINT_VERSION,
        "policy": POLICY_DESCRIPTOR,
        "policy_sha256": POLICY_SHA256,
        "benchmark_guard_sha256": guard.manifest_sha256,
        "raw_data_mutated": False,
    }
    if path.exists():
        existing = json.loads(path.read_text(encoding="utf-8"))
        for key in ("fingerprint_version", "policy_sha256", "benchmark_guard_sha256"):
            if existing.get(key) != payload[key]:
                raise RuntimeError(f"Preprocess manifest {key} mismatch")
    atomic_json(path, payload)


def record_error(staging_root: Path, candidate: ArchiveCandidate, exc: BaseException) -> bool:
    # A durable success report is authoritative. This guard also prevents a
    # late exception handler from recreating the legacy both-present state.
    if report_path(staging_root, candidate.bucket, candidate.index).exists():
        durable_unlink(error_path(staging_root, candidate.bucket, candidate.index))
        return False
    details = (
        exc.error_details()
        if isinstance(exc, OperationalPreprocessError)
        else {"error_code": "archive_validation_or_processing_error"}
    )
    atomic_json(
        error_path(staging_root, candidate.bucket, candidate.index),
        {
            "error_version": 1,
            "archive": candidate.relative_path,
            "archive_size": candidate.path.stat().st_size,
            "error_type": type(exc).__name__,
            "error": str(exc),
            "recorded_at_unix": int(time.time()),
            **details,
        },
    )
    return True


