def analyze_document(content: bytes, bucket: str) -> dict[str, Any]:
    try:
        text = content.decode("utf-8", errors="strict")
    except UnicodeDecodeError as exc:
        raise ValueError(f"Raw member is not valid UTF-8: {exc}") from exc
    normalized = normalize_content(text, bucket)
    metrics, flags = quality_metrics(text, content, bucket)
    language = "Python" if bucket == "python" else "English" if not bucket_is_code(bucket) else "Other"
    benchmark_reason = _WORKER_GUARD.contamination_reason(language, text) if _WORKER_GUARD else None
    if benchmark_reason:
        flags = sorted(set([*flags, "benchmark_contamination"]))
    return {
        "content_sha256": hashlib.sha256(content).hexdigest(),
        "normalized_sha256": hashlib.sha256(normalized.encode("utf-8")).hexdigest(),
        "near_sketch": bottom_k_sketch(near_features(normalized, bucket)),
        "metrics": metrics,
        "quality_flags": flags,
        "benchmark_reason": benchmark_reason,
        "size_bytes": len(content),
    }


def analyze_document_batch(contents: list[bytes], bucket: str) -> list[dict[str, Any]]:
    """Analyze a batch in one worker IPC call while preserving input order."""
    return [analyze_document(content, bucket) for content in contents]


