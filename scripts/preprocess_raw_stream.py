def status_payload(
    root: Path,
    staging_root: Path,
    index: DedupIndex | None,
    *,
    quota_path: Path = DEFAULT_QUOTAS,
    dedup_unavailable_reason: str = "optional fingerprint telemetry disabled",
) -> dict[str, Any]:
    reconciled_errors = reconcile_published_states(staging_root)
    reports = list(iter_reports(staging_root))
    coverage = report_coverage_payload(root, staging_root)
    by_bucket: dict[str, dict[str, int]] = {}
    for report in reports:
        bucket = str(report["bucket"])
        row = by_bucket.setdefault(bucket, {"archives": 0, "documents": 0, "tokens": 0})
        row["archives"] += 1
        row["documents"] += int(report["documents"])
        row["tokens"] += int(report["exact_tokens"])
    finalized_by_bucket: dict[str, dict[str, int]] = {}
    for record in load_quota_records(root).values():
        bucket = quota_record_bucket(record)
        if bucket is None:
            continue
        row = finalized_by_bucket.setdefault(bucket, {"archives": 0, "documents": 0, "tokens": 0})
        row["archives"] += 1
        row["documents"] += int(record.get("documents") or 0)
        row["tokens"] += int(record.get("exact_tokens") or 0)
    for bucket, finalized in finalized_by_bucket.items():
        audited = by_bucket.setdefault(bucket, {"archives": 0, "documents": 0, "tokens": 0})
        audited["finalized_archives"] = finalized["archives"]
        audited["finalized_documents"] = finalized["documents"]
        audited["finalized_tokens"] = finalized["tokens"]
        audited["coverage_percent"] = round(
            100.0 * audited["tokens"] / finalized["tokens"], 3
        ) if finalized["tokens"] else 100.0
    audited_tokens = sum(row["tokens"] for row in by_bucket.values())
    finalized_tokens = sum(row["tokens"] for row in finalized_by_bucket.values())
    if index is None:
        dedup_status = _unavailable_dedup_status(
            reports, audited_tokens, dedup_unavailable_reason
        )
    else:
        try:
            index.backfill_archive_tokens(reports)
            dedup_status = {"available": True, **index.status()}
            if dedup_status["ingested_archives"] > len(reports):
                raise RuntimeError(
                    "Dedup index contains more archives than the immutable report set"
                )
            if dedup_status["tokens"] > audited_tokens:
                raise RuntimeError(
                    "Dedup index contains more tokens than the immutable report set"
                )
            dedup_status["fingerprint_archives_pending_index"] = (
                len(reports) - dedup_status["ingested_archives"]
            )
            dedup_status["fingerprint_tokens_pending_index"] = (
                audited_tokens - dedup_status["tokens"]
            )
            if dedup_status["documents"]:
                dedup_status["exact_duplicate_percent"] = round(
                    100.0
                    * dedup_status["exact_duplicate_documents"]
                    / dedup_status["documents"],
                    3,
                )
                dedup_status["normalized_duplicate_percent"] = round(
                    100.0
                    * dedup_status["normalized_duplicate_documents"]
                    / dedup_status["documents"],
                    3,
                )
        except (OSError, sqlite3.Error, RuntimeError, ValueError) as exc:
            dedup_status = _unavailable_dedup_status(
                reports,
                audited_tokens,
                f"optional fingerprint telemetry unavailable: {type(exc).__name__}: {exc}",
            )
    archive_errors = (
        len(list((staging_root / "errors").glob("*/*.json")))
        if (staging_root / "errors").exists()
        else 0
    )
    raw_audit_complete = bool(coverage["complete"] and archive_errors == 0)
    return {
        "snapshot_unix": int(time.time()),
        "policy_sha256": POLICY_SHA256,
        "raw_audit_complete": raw_audit_complete,
        "collection_closure": collection_closure_payload(
            root, quota_path, staging_root=staging_root
        ),
        "report_coverage": coverage,
        "finalized_archives_waiting": int(coverage["missing_reports"]),
        "archive_errors": archive_errors,
        "legacy_stale_errors_reconciled": reconciled_errors,
        "audited_tokens": audited_tokens,
        "finalized_tokens": finalized_tokens,
        "audit_coverage_percent": round(100.0 * audited_tokens / finalized_tokens, 3)
        if finalized_tokens
        else 100.0,
        "audited": dict(sorted(by_bucket.items())),
        "dedup_index": dedup_status,
    }


def write_status_snapshot(
    root: Path,
    staging_root: Path,
    index: DedupIndex | None,
    *,
    quota_path: Path = DEFAULT_QUOTAS,
    dedup_unavailable_reason: str = "optional fingerprint telemetry disabled",
) -> dict[str, Any]:
    payload = status_payload(
        root,
        staging_root,
        index,
        quota_path=quota_path,
        dedup_unavailable_reason=dedup_unavailable_reason,
    )
    atomic_json(staging_root / "STATUS.json", payload)
    return payload


def terminal_gate_failures(
    snapshot: dict[str, Any],
    *,
    require_index_complete: bool = False,
    require_closed_collection: bool = False,
) -> list[str]:
    failures: list[str] = []
    if not snapshot.get("raw_audit_complete"):
        failures.append("raw report coverage is incomplete or archive errors remain")
    if require_closed_collection and not snapshot.get("collection_closure", {}).get(
        "complete"
    ):
        failures.append("collection is not closed by exact quota/marker/raw identities")
    if require_index_complete:
        dedup = snapshot.get("dedup_index", {})
        if not dedup.get("available", True):
            failures.append("fingerprint telemetry index is unavailable")
        else:
            pending = int(dedup.get("fingerprint_archives_pending_index", -1))
            if pending != 0:
                failures.append(f"fingerprint telemetry index has {pending} archives pending")
    return failures


